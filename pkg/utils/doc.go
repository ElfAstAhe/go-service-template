// Package utils инкапсулирует в себе набор высокопроизводительных, потокобезопасных
// утилит общего назначения, обслуживающих системную инфраструктуру Enterprise-шаблона.
//
// В состав пакета входят следующие ключевые компоненты:
//
//  1. Криптографический слой (Cipher / AesGcmCipher):
//     Обеспечивает симметричное аутентифицированное шифрование (AEAD) данных в рантайме.
//
//  2. Потоковые декомпрессоры (DecompressReader):
//     Выполняют распаковку бинарных потоков «на лету» для популярных сетевых алгоритмов
//     сжатия данных (Gzip, Deflate, LZW, Brotli).
//
//  3. Высококонкурентные коллекции (ConcurrentList):
//     Потокобезопасные обобщенные (Generic) динамические списки, полностью интегрированные
//     с нативными итераторами Go (iter.Seq / iter.Seq2) для безопасной lock-free итерации.
