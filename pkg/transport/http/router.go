package http

import (
	"net/http"
)

// Router определяет унифицированный, абстрактный контракт для подсистемы HTTP-маршрутизации (Router Contract).
//
// Абстрагирует инфраструктурный HTTP-раннер от конкретной библиотеки роутинга (chi, gin, httprouter или стандартный ServeMux).
// Возвращает каноничный интерфейс http.Handler, что гарантирует бесшовное встраивание любых слоев Middleware,
// CORS-фильтров и интерцепторов логирования/метрирования, принятых в экосистеме Go.
type Router interface {
	// GetRouter возвращает сконфигурированный, потокобезопасный сетевой диспетчер запросов в виде http.Handler.
	GetRouter() http.Handler
}
