package worker

// Scheduler описывает унифицированный контракт для фоновых периодических планировщиков задач (Task Scheduler Contract).
//
// Выступает в роли базового маркера для компонентов, выполняющих работу по расписанию,
// таймерам или тикерам (например, фоновые ворки очистки сессий, сборщики метрик, Janitor-процессы).
// Наследует общий жизненный цикл потоков фреймворка, гарантируя корректное гашение задач при Graceful Shutdown.
type Scheduler interface {
	CommonWorker // Наследует каноничные методы управления горутинами: Start, Stop и хелсчеки состояния
}
