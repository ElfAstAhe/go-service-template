package app

// Application описывает ультимативный, центральный контракт жизненного цикла микросервиса (Application Lifecycle Contract).
//
// Регламентирует строго упорядоченный четырехфазный рантайм-паспорт приложения.
// Полностью инкапсулирует рутину сборки, оркестрации IoC/DI контейнеров, обработки сигналов ОС
// и мягкого высвобождения ресурсов (Graceful Shutdown), превращая main.go в чистую декларативную точку входа.
type Application interface {
	// Init выполняет фазу холодного старта (Bootstrap Phase).
	// Отвечает за инициализацию логгеров, парсинг Viper-конфигураций и сборку графа зависимостей оркестратора.
	Init() error

	// Run запускает асинхронный рантайм-цикл приложения (Execution Phase).
	// Поднимает сетевые HTTP/gRPC серверы и многопоточные консьюмеры очередей брокеров внутри выделенных горутин.
	Run() error

	// Stop инициирует процедуру мягкой остановки выполнения (Graceful Shutdown Phase) при перехвате сигналов SIGTERM/SIGINT.
	// Принудительно гасит прием нового сетевого трафика, выделяя воркерам фиксированное время на обработку текущих задач.
	Stop() error

	// Close выполняет финальную фазу тотальной очистки ресурсов (Resource Disposing Phase).
	// Каскадно уничтожает пулы соединений СУБД, закрывает файловые дескрипторы и сокеты кэшей, исключая утечки памяти на ноде.
	Close() error
}
