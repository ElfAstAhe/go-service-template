package migration

import (
	"context"
)

// Migrator описывает абстрактный, агностичный контракт для управления схемами баз данных (Database Migrator).
//
// Обеспечивает выполнение требований эволюции и версионирования структуры хранения данных (DDL):
//  1. Initialize отвечает за подготовку системных таблиц отслеживания версий миграций в целевой СУБД.
//  2. Интеграция с context.Context в методах Up/Down гарантирует строгий контроль таймаутов при деплое (CI/CD).
type Migrator interface {
	// Initialize выполняет предварительную настройку окружения (например, создает таблицу schema_migrations).
	Initialize() error

	// Up атомарно накатывает незавершенные миграции, переводя структуру БД на самую свежую версию схемы.
	Up(ctx context.Context) error

	// Down производит последовательный откат структуры базы данных на предыдущую или нулевую версию схемы.
	Down(ctx context.Context) error
}
