// Package jwt предоставляет унифицированные инструменты для выпуска, парсинга,
// криптографической верификации и извлечения утверждений (Claims) из JWT-токенов
// на базе библиотеки ://github.com.
//
// # Архитектура и разделение ответственности
//
// Пакет построен вокруг принципа разделения интерфейсов (ISP) и единой ответственности (SRP):
//   - SubjectClaims и SubjectClaimsBuilder: доменная модель полезной нагрузки токена (Payload),
//     расширяющая стандартные утверждения jwt.RegisteredClaims полями идентичности субъекта
//     (SubjectID, SubjectType) и списком RBAC-ролей (Roles). Конструирование выполняется
//     через потокобезопасный при локальном использовании Fluent Builder с автоматическим сбросом
//     состояния в терминальном методе Build.
//   - TokenFactory (реализация Factory): контур эмиссии токенов (Identity Provider). Отвечает за
//     валидацию бизнес-инвариантов субъекта, сборку объекта jwt.Token и его криптографическую подпись.
//   - TokenExtractor (реализация Extractor): контур верификации и разбора токенов. Разделяет
//     проверку алгоритма и цифровой подписи (метод Token) от валидации временных меток
//     (exp, nbf, iat с учетом Leeway), издателя (iss), целевой аудитории (aud) и полей
//     субъекта (метод Claims).
//   - Транспортные адаптеры (HTTPExtractor, GRPCExtractor): инкапсулируют извлечение сырых
//     строк токенов из HTTP-заголовков, cookie и метаданных gRPC (metadata.MD) с последующей
//     передачей в TokenExtractor.
//
// # Безопасность
//
//   - Защита от атак Algorithm Confusion обеспечивается строгим белым списком допустимых
//     алгоритмов подписи (jwt.WithValidMethods) на этапе парсинга токена.
//   - Валидация периметра (Audience) предотвращает использование токенов, выпущенных для
//     других микросервисов экосистемы.
