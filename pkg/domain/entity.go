package domain

// Entity описывает универсальный, строго типизированный (Generic) контракт базовой доменной сущности.
//
// Объединяет в себе механизмы идентификации и хуки жизненного цикла (Hooks/Lifecycles/Validation).
// Позволяет базовым SQL-движкам репозиториев (DAL) прозрачно оперировать сущностями,
// автоматически выполняя пред-обработку и проверку инвариантов перед фиксацией изменений в базе данных.
type Entity[ID comparable] interface {
	// GetID возвращает уникальный первичный ключ (идентификатор) текущей сущности.
	GetID() ID

	// SetID принудительно выставляет первичный ключ (например, при генерации UUID на стороне приложения).
	SetID(id ID)

	// IsExists возвращает признак того, зафиксирована ли уже данная сущность в постоянном хранилище (СУБД).
	// Помогает стратегиям сохранения (Save) автоматически выбирать между операциями INSERT и UPDATE.
	IsExists() bool

	// BeforeCreate — хук пред-обработки сущности, выполняемый строго до совершения INSERT-транзакции.
	BeforeCreate() error

	// BeforeChange — хук пред-обработки сущности, выполняемый строго до совершения UPDATE-транзакции.
	BeforeChange() error

	// ValidateCreate проверяет бизнес-ограничения и инварианты сущности перед её первоначальным созданием.
	ValidateCreate() error

	// ValidateChange проверяет бизнес-ограничения и инварианты сущности перед обновлением её полей.
	ValidateChange() error
}

// SoftDeleteEntity расширяет контракт доменного слоя для поддержки паттерна «Мягкого удаления» (Soft Delete).
//
// Исключает физическое стирание строк из таблиц баз данных, переводя сущности в статус неактивных
// за счет выставления специализированных флагов или наносекундных меток времени (DEL).
type SoftDeleteEntity[DEL any] interface {
	// GetDeleted возвращает текущее значение флага/метки удаления сущности.
	GetDeleted() DEL

	// SetDeleted переводит сущность в статус удаленной, фиксируя маркер удаления.
	SetDeleted(deleted DEL)

	// IsDeleted возвращает булев признак того, считается ли данный объект логически удаленным из системы.
	IsDeleted() bool
}
