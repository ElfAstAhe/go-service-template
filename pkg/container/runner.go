package container

import (
	"context"
)

// Runner описывает универсальный, агностичный контракт управления жизненным циклом активных рантайм-компонентов.
//
// Выступает в роли унифицированного интерфейса для серверов (HTTP/gRPC) и фоновых планировщиков (Workers/Consumers),
// позволяя DI-оркестраторам централизованно координировать процессы параллельного запуска и мягкой остановки (Graceful Shutdown).
type Runner interface {
	// GetName возвращает уникальное текстовое наименование компонента (например, "grpc-server", "kafka-consumer-worker").
	// Применяется для изоляции контекстов логирования, трассировки вызовов и сбора системных метрик.
	GetName() string

	// Start инициирует запуск основного асинхронного цикла выполнения компонента (обычно внутри выделенной горутины).
	// Протаскивание ctx позволяет контролировать общую продолжительность жизни приложения.
	Start(ctx context.Context) error

	// Stop запускает процедуру контролируемой мягкой остановки (Graceful Shutdown) компонента.
	// Принимает выделенный stopCtx с жестким таймаутом, гарантируя корректное завершение текущих сетевых транзакций.
	Stop(stopCtx context.Context) error

	// IsRunning возвращает текущий атомарный статус активности компонента.
	// Используется хелсчеками (Health Checks) для валидации работоспособности внутренних потоков.
	IsRunning() bool
}
