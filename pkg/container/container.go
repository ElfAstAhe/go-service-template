package container

import (
	"context"
)

// Container интерфейс контейнера (Inversion of Control / Dependency Injection Contract)
//
// Определяет атомарный базовый контракт для управления изолированными модулями зависимостей.
// Отвечает за хранение, ручную регистрацию инстансов, проверку их состояния, а также
// предоставляет методы для централизованной инициализации и очистки выделенных ресурсов.
type Container interface {
	// GetName возвращает уникальное текстовое имя контейнера (например, "InfraContainer", "CacheContainer").
	// Применяется оркестратором для логирования шагов сборки и адресации ошибок в графе зависимостей.
	GetName() string

	// Init запускает процесс выделения ресурсов и подготовки внутренних компонентов контейнера.
	// Ограничен контекстом ctx для контроля таймаутов холодного старта (Bootstrap phase).
	Init(ctx context.Context) error

	// Close производит каскадное закрытие и очистку всех удерживаемых контейнером персистентных пулов и сокетов.
	// Гарантирует отсутствие утечек дескрипторов при остановке приложения по Graceful Shutdown.
	Close(ctx context.Context) error

	// RegisterInstance динамически добавляет уже готовый, собранный объект (instance) в реестр под уникальным именем.
	RegisterInstance(name string, instance any) error

	// UnregisterInstance атомарно удаляет созданный живой объект из внутренней памяти контейнера.
	UnregisterInstance(name string) error

	// GetInstance извлекает нетипизированный объект (any) из реестра контейнера по его имени.
	// Возвращает ошибку ContainerNotFoundError, если зависимость не найдена или зафейлилась при сборке.
	GetInstance(name string) (any, error)

	// IsRegistered проверяет, зарегистрирован ли в контейнере компонент (или его фабрика-провайдер) под данным именем.
	IsRegistered(name string) bool

	// HasInstance проверяет, создан и кэширован ли в оперативной памяти контейнера живой физический объект.
	HasInstance(name string) bool

	// AllNames возвращает полный массив строковых имен всех зарегистрированных в текущем модуле компонентов.
	AllNames() []string
}
