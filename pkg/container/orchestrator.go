package container

import (
	"context"
)

// Orchestrator описывает центральный контракт IoC/DI-оркестратора фреймворка (Container Orchestrator).
//
// Координирует жизненный цикл и иерархию независимых инфраструктурных контейнеров (Containers).
// Отвечает за сквозную инициализацию ресурсов, каскадное закрытие пулов соединений (Resource Cleanup)
// и агрегацию исполняемых компонентов (Runners) для передачи их в главный цикл main.go.
type Orchestrator interface {
	// Init запускает последовательную или топологическую инициализацию всех зарегистрированных контейнеров.
	// Протаскивание ctx гарантирует контроль таймаутов на этапе холодного старта (Bootstrap phase).
	Init(ctx context.Context) error

	// Close запускает каскадное контролируемое гашение всех удерживаемых контейнерами ресурсов (баз данных, сокетов, кэшей).
	// Вызывается в рамках Graceful Shutdown строго после остановки всех исполняемых горутин-раннеров.
	Close(ctx context.Context) error

	// Register динамически добавляет новый инфраструктурный или бизнес-контейнер в глобальный реестр оркестратора.
	Register(container Container) error

	// Unregister атомарно исключает контейнер из реестра по его строковому идентификатору.
	Unregister(name string) error

	// GetContainer извлекает зарегистрированный контейнер по его уникальному имени.
	// Возвращает типизированную ошибку ContainerNotFoundError, если компонент отсутствует в графе сборки.
	GetContainer(name string) (Container, error)

	// HasContainer выполняет быструю атомарную проверку факта регистрации контейнера в реестре.
	HasContainer(name string) bool

	// AllContainers возвращает плоский срез всех активных контейнеров для проведения сквозного аудита зависимостей.
	AllContainers() []Container

	// GetRunners опрашивает зарегистрированные контейнеры и собирает с них все исполняемые компоненты (Runners),
	// подлежащие асинхронному запуску в горутинах (HTTP/gRPC серверы, фоновые воркеры брокеров).
	GetRunners() ([]Runner, error)
}
