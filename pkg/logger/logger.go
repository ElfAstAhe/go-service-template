package logger

// Logger описывает центральный абстрактный контракт подсистемы логирования фреймворка.
//
// Объединяет классическое текстовое логирование, форматированный вывод (printf-style)
// и высокопроизводительное структурированное логирование (структура ключ-значение).
// Поддерживает иерархическое ветвление логгеров для изоляции контекстов компонентов (Sub-Loggers).
type Logger interface {
	// ====================================================================
	// Структурированное логирование (Structured Logging)
	// ====================================================================
	// Принимают сообщение и нечетное/четное количество аргументов в формате пар [Ключ, Значение].
	// Оптимизированы для автоматического сбора и индексации в системах агрегации (Loki, ELK, Splunk).
	// Пример вызова: log.InfoW("user login successful", "id", user.GetID(), "ip", transport.RealIP(ctx))

	// InfoW фиксирует штатные высокоуровневые события рантайма с бизнес-контекстом.
	InfoW(msg string, keysAndValues ...any)
	// WarnW логирует некритичные аномалии, временные сетевые сбои или работу ретраев брокеров.
	WarnW(msg string, keysAndValues ...any)
	// ErrorW регистрирует критические системные сбои, отказы БД или фатальные нарушения инвариантов.
	ErrorW(msg string, keysAndValues ...any)
	// DebugW выводит подробные технические трассировки сокетов и памяти для отладки на стейджинге.
	DebugW(msg string, keysAndValues ...any)

	// ====================================================================
	// Простые неформатированные логи (Basic Logging)
	// ====================================================================
	// Принимают произвольный массив аргументов и выводят их в виде плоского текста.

	Error(args ...any)
	Warn(args ...any)
	Info(args ...any)
	Debug(args ...any)

	// ====================================================================
	// Форматированные логи (Printf-Style Logging)
	// ====================================================================
	// Поддерживают стандартные глаголы форматирования Go (вроде %s, %d, %+v).

	Errorf(format string, args ...any)
	Warnf(format string, args ...any)
	Infof(format string, args ...any)
	Debugf(format string, args ...any)

	// ====================================================================
	// Управление жизненным циклом и контекстом (Lifecycle & Context)
	// ====================================================================

	// GetLogger порождает изолированный дочерний экземпляр логгера (Sub-Logger).
	// Новый логгер намертво приклеивает маркер logicEntry к метаданным каждой последующей строки лога.
	// Используется для изоляции логов конкретных воркеров или репозиториев (например, "kafka-receiver").
	GetLogger(logicEntry string) Logger

	// Close осуществляет мягкую остановку подсистемы логирования, принудительно
	// сбрасывая все накопленные в памяти буферы на диск или в stdout (Flush).
	Close() error
}
